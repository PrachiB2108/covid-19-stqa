-- COVID-19 Information & Awareness Portal - PostgreSQL schema
-- Connect to the target database before running this file.
-- This schema intentionally does not create/drop a database or existing tables.

CREATE TABLE users (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY,
  full_name   VARCHAR(50)  NOT NULL,
  email       VARCHAR(100) NOT NULL,
  phone       CHAR(10)     NOT NULL,
  password    VARCHAR(255) NOT NULL, -- password_hash() output
  role        VARCHAR(5)   NOT NULL DEFAULT 'user',
  created_at  TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT pk_users PRIMARY KEY (id),
  CONSTRAINT ck_users_role CHECK (role IN ('user', 'admin'))
);

-- Match the app's case-insensitive email handling.
CREATE UNIQUE INDEX uq_users_email ON users (LOWER(email));

CREATE TABLE comments (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY,
  user_id     BIGINT       NOT NULL,
  comment     VARCHAR(500) NOT NULL,
  status      VARCHAR(7)   NOT NULL DEFAULT 'visible',
  created_at  TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT pk_comments PRIMARY KEY (id),
  CONSTRAINT ck_comments_status CHECK (status IN ('visible', 'hidden')),
  CONSTRAINT fk_comments_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);
CREATE INDEX idx_comments_user ON comments (user_id);

-- Contact / registration submissions. Guests have a NULL user_id.
CREATE TABLE registrations (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY,
  user_id     BIGINT       NULL,
  name        VARCHAR(50)  NOT NULL,
  email       VARCHAR(100) NOT NULL,
  phone       CHAR(10)     NOT NULL,
  message     VARCHAR(500) NOT NULL,
  created_at  TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT pk_registrations PRIMARY KEY (id),
  CONSTRAINT fk_reg_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE SET NULL
);
CREATE INDEX idx_reg_user ON registrations (user_id);

-- Durable PHP sessions for serverless hosts whose function filesystems are ephemeral.
CREATE TABLE sessions (
  session_id   VARCHAR(256) PRIMARY KEY,
  session_data TEXT        NOT NULL,
  last_activity BIGINT     NOT NULL
);
CREATE INDEX idx_sessions_activity ON sessions (last_activity);
